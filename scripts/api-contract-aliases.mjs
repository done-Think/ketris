import fs from 'node:fs'
import path from 'node:path'
import ts from 'typescript'

export function collectApiAliases(root, load) {
  const server = path.join(root, 'apps/web/src/server')
  const files = []
  const visit = (directory) => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const file = path.join(directory, entry.name)
      if (entry.isDirectory()) visit(file)
      else if (file.includes('/types/') && file.endsWith('.ts')) files.push(file)
    }
  }
  visit(server)
  const aliases = []

  for (const file of files.sort()) {
    const text = fs.readFileSync(file, 'utf8')
    const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true)
    const imports = new Map()
    for (const node of source.statements) {
      if (!ts.isImportDeclaration(node) || !ts.isStringLiteral(node.moduleSpecifier)) continue
      const bindings = node.importClause?.namedBindings
      if (bindings && ts.isNamedImports(bindings))
        for (const name of bindings.elements)
          imports.set(name.name.text, {
            module: node.moduleSpecifier.text,
            name: (name.propertyName ?? name.name).text,
          })
    }
    for (const node of source.statements) {
      if (!ts.isTypeAliasDeclaration(node)) continue
      const references = []
      const find = (child) => {
        if (
          ts.isTypeReferenceNode(child) &&
          /^z\.(infer|input|output)$/.test(child.typeName.getText(source))
        )
          references.push(child)
        ts.forEachChild(child, find)
      }
      find(node.type)
      if (references.length !== 1) continue
      const type = references[0].getText(source).replace(/\s+/g, ' ')
      let module
      let name
      const imported =
        /^z\.(?:infer|input|output)<\s*typeof import\(['"]([^'"]+)['"]\)\.([\w]+)\s*>$/.exec(type)
      const named = /^z\.(?:infer|input|output)<\s*typeof ([\w]+)\s*>$/.exec(type)
      if (imported) [, module, name] = imported
      else if (named) ({ module, name } = imports.get(named[1]) ?? {})
      if (!module || !name) continue
      let target
      if (module.startsWith('@server/')) target = path.join(server, module.slice(8))
      else if (module.startsWith('@shared/'))
        target = path.join(root, 'apps/web/src/shared', module.slice(8))
      else if (module.startsWith('.')) target = path.resolve(path.dirname(file), module)
      else continue
      const schema = load(target, import.meta.url)[name]
      if (!schema?._def) continue
      const component = schema._def.openapi?._internal?.refId ?? node.name.text.replace(/DTO$/, '')
      const partial = /^Partial</.test(node.type.getText(source).replace(/\s+/g, ''))
      aliases.push({
        file,
        name: node.name.text,
        component,
        schema,
        schemaFile: target,
        schemaName: name,
        partial,
      })
    }
  }
  return aliases
}

export function apiAliasFiles(root, aliases, components) {
  const groups = new Map()
  for (const alias of aliases) {
    if (!components[alias.component]) continue
    const relative = path.relative(path.join(root, 'apps/web/src/server'), alias.file)
    const key = relative.replace('/types/', '/')
    if (!groups.has(key)) groups.set(key, [])
    groups.get(key).push(alias)
  }
  return [...groups].map(([key, values]) => ({
    file: path.join(root, 'apps/web/src/shared/types/generated', key),
    source:
      "import type { components } from '../api'\n\n" +
      values
        .map(
          ({ name, component, partial }) =>
            `export type ${name} = ${partial ? 'Partial<' : ''}components['schemas'][${JSON.stringify(component)}]${partial ? '>' : ''}`,
        )
        .join('\n') +
      '\n',
  }))
}

export function apiComponentRegistration(root, aliases) {
  const directory = path.join(root, 'apps/web/src/server/openapi')
  const unique = [...new Map(aliases.map((alias) => [alias.component, alias])).values()].sort(
    (a, b) => a.component.localeCompare(b.component, 'en'),
  )
  const imports = unique.map((alias, index) => {
    const relative = path.relative(directory, alias.schemaFile).replaceAll(path.sep, '/')
    return `import { ${alias.schemaName} as contractSchema${index} } from ${JSON.stringify(relative.startsWith('.') ? relative : './' + relative)}`
  })
  return [
    '// Generated by npm run api:generate.',
    "import type { OpenAPIRegistry } from '@asteasolutions/zod-to-openapi'",
    ...imports,
    '',
    'export function registerContractComponents(registry: OpenAPIRegistry) {',
    ...unique.map(
      (alias, index) =>
        `  registry.register(${JSON.stringify(alias.component)}, contractSchema${index})`,
    ),
    '}',
    '',
  ].join('\n')
}

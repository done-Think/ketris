import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath, pathToFileURL } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'
import prettier from 'prettier'
import {
  collectApiAliases,
  apiAliasFiles,
  apiComponentRegistration,
} from './api-contract-aliases.mjs'

const root = new URL('../', import.meta.url)
process.env.TSX_TSCONFIG_PATH = fileURLToPath(new URL('apps/web/tsconfig.json', root))
const { require: tsxRequire } = await import('tsx/cjs/api')
const aliases = collectApiAliases(fileURLToPath(root), tsxRequire)
const config = await prettier.resolveConfig(fileURLToPath(new URL('apps/web/.prettierrc', root)))
const registrationFile = new URL('apps/web/src/server/openapi/contract-components.ts', root)
const registration = await prettier.format(apiComponentRegistration(fileURLToPath(root), aliases), {
  ...config,
  parser: 'typescript',
})
if (process.argv.includes('--check')) {
  if ((await readFile(registrationFile, 'utf8').catch(() => '')) !== registration)
    throw new Error('API component registration is stale. Run npm run api:generate.')
} else {
  await writeFile(registrationFile, registration)
}
const registry = tsxRequire(
  fileURLToPath(new URL('apps/web/src/server/openapi/registry.ts', root)),
  import.meta.url,
)
const generation = registry.generateOpenApiDocument ?? registry.default?.generateOpenApiDocument
const document = generation()
const schema = JSON.parse(JSON.stringify(document))
const ast = await openapiTS(schema, { alphabetize: true, defaultNonNullable: false })
const output = new URL('apps/web/src/shared/types/generated/api.ts', root)
const types = await prettier.format('// Generated by npm run api:generate.\n' + astToString(ast), {
  ...config,
  parser: 'typescript',
})
const snapshot = new URL('apps/web/openapi.json', root)
const json = await prettier.format(JSON.stringify(schema), { ...config, parser: 'json' })

const bridges = await Promise.all(
  apiAliasFiles(fileURLToPath(root), aliases, schema.components.schemas).map(
    async ({ file, source }) => [
      pathToFileURL(file),
      await prettier.format(source, { ...config, parser: 'typescript' }),
    ],
  ),
)
for (const [file, expected] of [[output, types], [snapshot, json], ...bridges]) {
  if (process.argv.includes('--check')) {
    const actual = await readFile(file, 'utf8').catch(() => '')
    if (actual !== expected)
      throw new Error(
        `Generated API contract is stale: ${fileURLToPath(file)}. Run npm run api:generate.`,
      )
  } else {
    await mkdir(new URL('./', file), { recursive: true })
    await writeFile(file, expected)
  }
}
console.log(
  `${Object.keys(schema.paths).length} paths and ${Object.keys(schema.components.schemas).length} schemas generated/verified.`,
)
